import type { CaseItem, Client } from "./types";

export function draftPetition(kind: string, caseItem?: CaseItem, client?: Client) {
  const clientName = client?.fullName ?? "موکل";
  const title = caseItem?.title ?? "موضوع پرونده";
  const court = caseItem?.court || "مرجع صالح";
  const number = caseItem?.caseNumber || "—";
  const amount = caseItem?.claimAmount ? `${caseItem.claimAmount} ریال` : "مبلغ خواسته";

  const bodies: Record<string, string> = {
    appeal: `ریاست محترم دادگاه تجدیدنظر استان
با سلام
احتراماً در خصوص دادنامه صادره در پرونده کلاسه ${number} (موضوع: ${title}) از ${court}، اینجانب وکیل ${clientName} مراتب تجدیدنظرخواهی را به استناد ماده ۳۳۶ قانون آیین دادرسی مدنی به استحضار می‌رساند.

۱. رأی صادره از حیث استدلال با موازین قانونی انطباق ندارد.
۲. دلایل و مدارک ابرازی موکل مورد توجه کافی قرار نگرفته است.
۳. با عنایت به مستندات پیوست و ماده ۳۴۸ قانون آیین دادرسی مدنی، نقض دادنامه و صدور حکم شایسته مورد استدعاست.

این متن پیش‌نویس است و باید پیش از تقدیم بازبینی شود.`,
    defense: `ریاست محترم ${court}
با سلام
احتراماً در مقام دفاع از ${clientName} در پرونده ${title} به کلاسه ${number} به استحضار می‌رساند:

۱. ادعاهای طرف مقابل فاقد دلیل کافی است (مواد ۱۲۵۷ و ۱۲۵۸ قانون مدنی).
۲. مدارک پیوست، مالکیت و حسن‌نیت موکل را اثبات می‌کند.
۳. صدور حکم به رد دعوای خواهان مورد تقاضاست.

این متن پیش‌نویس است و باید پیش از تقدیم بازبینی شود.`,
    petition: `ریاست محترم ${court || "دادگاه عمومی حقوقی"}
با سلام
خواهان: ${clientName}
خوانده: ...............
خواسته: ${title}${caseItem?.claimAmount ? ` به مبلغ ${amount}` : ""}

دلایل و منضمات: رونوشت مدارک شناسایی، مستندات مثبت ادعا، وکالتنامه.

شرح دادخواست:
احتراماً به استحضار می‌رساند ${clientName} با استناد به مدارک پیوست، تقاضای صدور حکم بر محکومیت خوانده به ${title} را دارد. مستنداً به مواد قانون مدنی و آیین دادرسی مدنی، رسیدگی و صدور حکم شایسته مورد استدعاست.

محل امضا
این متن پیش‌نویس است و باید پیش از تقدیم بازبینی شود.`,
    expert: `ریاست محترم ${court}
با سلام
احتراماً نسبت به نظریه کارشناسی ابلاغ‌شده در پرونده ${title} (کلاسه ${number}) ظرف مهلت ماده ۲۶۰ قانون آیین دادرسی مدنی اعتراض می‌گردد.

جهات اعتراض:
۱. نظریه با اوضاع و احوال محقق قضیه مطابقت ندارد.
۲. کارشناس از برخی جهات مورد ارجاع خارج شده است.
تقاضای ارجاع به هیئت کارشناسی مورد استدعاست.

این متن پیش‌نویس است و باید پیش از تقدیم بازبینی شود.`,
    execution: `ریاست محترم اجرای احکام ${court}
با سلام
احتراماً با استناد به دادنامه قطعی پرونده ${title} به کلاسه ${number} تقاضای صدور اجرائیه و تعقیب عملیات اجرایی به نفع ${clientName} را دارد.

این متن پیش‌نویس است و باید پیش از تقدیم بازبینی شود.`,
    settlement: `ریاست محترم ${court}
با سلام
احتراماً طرفین پرونده ${title} (کلاسه ${number}) آمادگی خود را برای سازش در حدود قانون اعلام می‌دارند. تقاضای صورت‌جلسه سازش و گزارش اصلاحی مورد استدعاست.

این متن پیش‌نویس است و باید پیش از تقدیم بازبینی شود.`,
  };

  return bodies[kind] ?? bodies.petition;
}
